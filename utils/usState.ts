function normalizeStateToken(value: string): string {
  return value
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9\s]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

export function normalizeUsStateCode(state: string | undefined | null): string {
  if (!state) return '';

  const normalized = normalizeStateToken(state);
  if (!normalized) return '';
  if (normalized.length === 2) return normalized.toUpperCase();

  return US_STATE_ABBR_MAP[normalized] || normalized.toUpperCase();
}
